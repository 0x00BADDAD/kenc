package space.unmei.ast.exps;


public enum AstBinOpType {
    ADD,        // +
    SUBTRACT,   // -
    MULTIPLY,   // *
    DIVIDE,     // /
    MODULO,     // %

    EQUAL,      // ==
    NOT_EQUAL,  // !=

    LESS_THAN,      // <
    GREATER_THAN,   // >
    LESS_EQUAL,     // <=
    GREATER_EQUAL,  // >=

    LOGICAL_AND,    // and
    LOGICAL_OR,     // or
    BOOL_NEGATION,   // !

    DIS, // |
    CON  // &


}
